    SImage renderSpaceIcon(std::string_view key, const SRgba& color, int size) {
        if (size <= 0 || size > MAX_SPACE_ICON_SIZE || static_cast<size_t>(size) > MAX_RASTER_BYTES / 4 / static_cast<size_t>(size) || !std::isfinite(color.r) ||
            !std::isfinite(color.g) || !std::isfinite(color.b) || !std::isfinite(color.a))
            return {};
        if (!spaces::validSpaceIcon(key))
            key = spaces::DEFAULT_SPACE_ICON;
        auto found = std::ranges::find(ICON_SVGS, key, &SIconSvg::key);
        if (found == ICON_SVGS.end())
            found = std::ranges::find(ICON_SVGS, spaces::DEFAULT_SPACE_ICON, &SIconSvg::key);
        if (found == ICON_SVGS.end())
            return {};
        try {
            const auto channel = [](double value) { return static_cast<unsigned>(std::lround(std::clamp(value, 0.0, 1.0) * 255)); };
            auto       svg     = std::string(found->svg);
            svg.insert(svg.find('>'), std::format(R"( color="#{:02x}{:02x}{:02x}" opacity="{:.8f}")", channel(color.r), channel(color.g), channel(color.b),
                                                  std::clamp(color.a, 0.0, 1.0)));
            GError*                                      error = nullptr;
            const auto                                   unref = [](RsvgHandle* handle) { g_object_unref(handle); };
            std::unique_ptr<RsvgHandle, decltype(unref)> handle(rsvg_handle_new_from_data(reinterpret_cast<const guint8*>(svg.data()), svg.size(), &error), unref);
            if (error) {
                g_error_free(error);
                error = nullptr;
            }
            if (!handle)
                return {};
            std::unique_ptr<cairo_surface_t, decltype(&cairo_surface_destroy)> surface(cairo_image_surface_create(CAIRO_FORMAT_ARGB32, size, size),
                                                                                       cairo_surface_destroy);
            if (cairo_surface_status(surface.get()) != CAIRO_STATUS_SUCCESS)
                return {};
            std::unique_ptr<cairo_t, decltype(&cairo_destroy)> context(cairo_create(surface.get()), cairo_destroy);
            cairo_set_operator(context.get(), CAIRO_OPERATOR_SOURCE);
            cairo_set_source_rgba(context.get(), 0, 0, 0, 0);
            cairo_paint(context.get());
            cairo_set_operator(context.get(), CAIRO_OPERATOR_OVER);
            const RsvgRectangle viewport{0, 0, static_cast<double>(size), static_cast<double>(size)};
            const bool          rendered = rsvg_handle_render_document(handle.get(), context.get(), &viewport, &error);
            if (error)
                g_error_free(error);
            if (!rendered || cairo_status(context.get()) != CAIRO_STATUS_SUCCESS || cairo_surface_status(surface.get()) != CAIRO_STATUS_SUCCESS)
                return {};
            cairo_surface_flush(surface.get());
            const auto* pixels = cairo_image_surface_get_data(surface.get());
            const int   stride = cairo_image_surface_get_stride(surface.get());
            if (!pixels || stride <= 0)
                return {};
            SImage result{.w = size, .h = size, .stride = stride};
            result.data.assign(pixels, pixels + static_cast<size_t>(stride) * size);
            return result;
        } catch (const std::bad_alloc&) {
            return {};
        }
    }
